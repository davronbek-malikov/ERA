export function translate(locale: Locale, text: string, vars?: Record<string, string | number>): string {
  let out = locale === "uz" ? (UZ[text] ?? text) : text;
  if (vars) for (const [key, value] of Object.entries(vars)) out = out.split(`{${key}}`).join(String(value));
  return out;
}

/** Dates in the interface language (calendar dates are stored as YYYY-MM-DD). */
export function dateLocale(locale: Locale) {
  return locale === "uz" ? "uz-Latn-UZ" : "en-GB";
}
