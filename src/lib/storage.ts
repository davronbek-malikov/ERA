import { randomUUID } from "crypto";

import { slugify } from "@/lib/slugs";

/*
 * Storage layout (Prompt 07, docs/ERA_SECURITY_IMPLEMENTATION.md §5).
 *
 * Two buckets:
 *  - PRIVATE (`SUPABASE_STORAGE_VIDEOS_BUCKET`, default "course-videos"): lesson videos and course/lesson
 *    materials. Never linked directly: the server authorizes the learner, then issues a short-lived
 *    signed URL.
 *  - PUBLIC (`SUPABASE_STORAGE_PUBLIC_BUCKET`, optional): catalogue thumbnails, subject images, promo
 *    videos. Falls back to the private bucket name until it is configured, so existing deployments
 *    keep working unchanged.
 *
 * Object paths are always generated by the server: users/<userId>/<folder>/<YYYY-MM>/<uuid>-<name>.<ext>
 */

export type StorageVisibility = "public" | "private";

type FolderPolicy = {
  visibility: StorageVisibility;
  maxBytes: number;
  /** extension → accepted MIME types. Anything not listed (executables, SVG, HTML, scripts) is rejected. */
  types: Record<string, string[]>;
};

const MB = 1024 * 1024;

const imageTypes: Record<string, string[]> = {
  jpg: ["image/jpeg"],
  jpeg: ["image/jpeg"],
  png: ["image/png"],
  webp: ["image/webp"],
  gif: ["image/gif"],
  avif: ["image/avif"]
};

const videoTypes: Record<string, string[]> = {
  mp4: ["video/mp4"],
  m4v: ["video/mp4", "video/x-m4v"],
  webm: ["video/webm"],
  mov: ["video/quicktime"],
  ogv: ["video/ogg"]
};

const documentTypes: Record<string, string[]> = {
  pdf: ["application/pdf"],
  doc: ["application/msword"],
  docx: ["application/vnd.openxmlformats-officedocument.wordprocessingml.document"],
  ppt: ["application/vnd.ms-powerpoint"],
  pptx: ["application/vnd.openxmlformats-officedocument.presentationml.presentation"],
  xls: ["application/vnd.ms-excel"],
  xlsx: ["application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"],
  // Windows browsers report .csv as application/vnd.ms-excel.
  csv: ["text/csv", "application/vnd.ms-excel"],
  txt: ["text/plain"],
  zip: ["application/zip", "application/x-zip-compressed"],
  rar: ["application/vnd.rar", "application/x-rar-compressed"],
  "7z": ["application/x-7z-compressed"]
};

export const STORAGE_FOLDERS: Record<string, FolderPolicy> = {
  "course-thumbnails": { visibility: "public", maxBytes: 10 * MB, types: imageTypes },
  "subject-thumbnails": { visibility: "public", maxBytes: 10 * MB, types: imageTypes },
  images: { visibility: "public", maxBytes: 10 * MB, types: imageTypes },
  "course-promo-videos": { visibility: "public", maxBytes: 500 * MB, types: videoTypes },
  "lesson-videos": { visibility: "private", maxBytes: 500 * MB, types: videoTypes },
  "lesson-materials": { visibility: "private", maxBytes: 25 * MB, types: documentTypes },
  "course-materials": { visibility: "private", maxBytes: 25 * MB, types: documentTypes },
  // Knowledge Base sources (Prompt 09). The Knowledge Base also applies ERA_KB_MAX_FILE_MB and checks file signatures.
  "knowledge-documents": {
    visibility: "private",
    maxBytes: 25 * MB,
    types: {
      pdf: ["application/pdf"],
      docx: ["application/vnd.openxmlformats-officedocument.wordprocessingml.document"],
      txt: ["text/plain"],
      md: ["text/markdown", "text/x-markdown", "text/plain"],
      markdown: ["text/markdown", "text/x-markdown", "text/plain"]
    }
  }
};

export const MATERIAL_FOLDERS = new Set(["lesson-materials", "course-materials"]);

export function getSupabaseStorageConfig() {
  const supabaseUrl = (process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL)?.replace(/\/+$/, "");
  const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const bucket = process.env.SUPABASE_STORAGE_VIDEOS_BUCKET || "course-videos";
  const publicBucket = process.env.SUPABASE_STORAGE_PUBLIC_BUCKET || bucket;

  if (!supabaseUrl || !serviceRoleKey) {
    throw new Error("Supabase Storage is not configured on the server.");
  }

  return {
    supabaseUrl,
    serviceRoleKey,
    /** Private bucket (lesson videos, materials). Kept as `bucket` for backwards compatibility. */
    bucket,
    publicBucket
  };
}

export function isStorageConfigured() {
  return Boolean((process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL) && process.env.SUPABASE_SERVICE_ROLE_KEY);
}

export function bucketForFolder(folder: string) {
  const { bucket, publicBucket } = getSupabaseStorageConfig();
  return STORAGE_FOLDERS[folder]?.visibility === "public" ? publicBucket : bucket;
}

export function getFileExtension(filename: string) {
  const match = /\.([A-Za-z0-9]{1,8})$/.exec(filename);
  return match ? match[1].toLowerCase() : "";
}

/** Validates an upload request against the folder's policy. Returns a client-safe error message or null. */
export function validateUpload(folder: string, filename: string, contentType: string, fileSize: number): string | null {
  const policy = STORAGE_FOLDERS[folder];
  if (!policy) return "Invalid upload folder.";
  if (!Number.isFinite(fileSize) || fileSize <= 0) return "Invalid file size.";
  if (fileSize > policy.maxBytes) return "The selected file exceeds the size limit.";

  const extension = getFileExtension(filename);
  const accepted = policy.types[extension];
  if (!accepted) return "This file type is not allowed here.";
  if (!accepted.includes(contentType.toLowerCase())) return "The file type does not match its extension.";
  return null;
}

export function buildStoragePath(folder: string, filename: string) {
  const extension = getFileExtension(filename) || "bin";
  const safeName = slugify(filename.replace(/\.[^.]+$/, "")) || "file";
  const safeFolder = slugify(folder) || "uploads";
  const monthKey = new Date().toISOString().slice(0, 7);

  return `${safeFolder}/${monthKey}/${randomUUID()}-${safeName}.${extension}`;
}

export function buildUserScopedStoragePath(userId: string, folder: string, filename: string) {
  const basePath = buildStoragePath(folder, filename);
  const safeUserId = slugify(userId) || userId;

  return `users/${safeUserId}/${basePath}`;
}

export function getUserStoragePrefix(userId: string) {
  const safeUserId = slugify(userId) || userId;
  return `users/${safeUserId}/`;
}

/** Server-generated object paths only: no traversal, no absolute paths, no odd characters. */
export function isSafeStoragePath(path: string) {
  return (
    path.length > 0 &&
    path.length <= 512 &&
    /^users\/[A-Za-z0-9_-]+\/[a-z0-9-]+\/[A-Za-z0-9._/-]+$/.test(path) &&
    !path.split("/").some((segment) => segment === "" || segment === "." || segment === "..")
  );
}

/** The upload folder of a server-generated path (`users/<id>/<folder>/...`). */
export function storagePathFolder(path: string) {
  const segments = path.split("/");
  return segments[0] === "users" && segments.length > 3 ? segments[2] : null;
}

export function buildPublicObjectUrl(bucket: string, path: string) {
  const { supabaseUrl } = getSupabaseStorageConfig();
  return `${supabaseUrl}/storage/v1/object/public/${bucket}/${path}`;
}

/**
 * Recognises URLs that point at ERA's own storage (`…/storage/v1/object/public/<bucket>/<path>`).
 * Returns null for external URLs (YouTube, Vimeo, other hosts) or when storage is not configured.
 */
export function parseStorageObjectUrl(url: string): { bucket: string; path: string } | null {
  if (!isStorageConfigured()) return null;
  const { supabaseUrl, bucket, publicBucket } = getSupabaseStorageConfig();
  const prefix = `${supabaseUrl}/storage/v1/object/public/`;
  if (!url.startsWith(prefix)) return null;

  const rest = url.slice(prefix.length).split(/[?#]/)[0];
  const slash = rest.indexOf("/");
  if (slash <= 0) return null;
  const objectBucket = rest.slice(0, slash);
  let path: string;
  try {
    path = decodeURIComponent(rest.slice(slash + 1));
  } catch {
    return null;
  }
  if (objectBucket !== bucket && objectBucket !== publicBucket) return null;
  return { bucket: objectBucket, path };
}

/** @deprecated use parseStorageObjectUrl — kept for the delete route's `publicUrl` input. */
export function extractStoragePathFromPublicUrl(publicUrl: string) {
  return parseStorageObjectUrl(publicUrl)?.path ?? null;
}
